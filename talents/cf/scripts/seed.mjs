// Seed the local D1 from the P0/P1 registry files
// (../data/registry.json + ../data/fallback-registry.json, merged with
// the main registry winning id conflicts — the same merge the P1 CLI
// used). Emits seed.sql next to this script's package (cf/seed.sql);
// `npm run seed` applies migrations and executes it against local D1.
//
// Requires the root engine to be built (../../dist) for toSearchDocument
// so the FTS documents match the P1 search document shape exactly.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { toSearchDocument } from "../../dist/src/search.js";

const CF = resolve(dirname(new URL(import.meta.url).pathname), "..");
const DATA = resolve(CF, "../data");

const byId = new Map();
for (const f of ["registry.json", "fallback-registry.json"]) {
  const path = resolve(DATA, f);
  if (!existsSync(path)) continue;
  const parsed = JSON.parse(readFileSync(path, "utf8"));
  for (const r of Object.values(parsed.records ?? {})) if (!byId.has(r.id)) byId.set(r.id, r);
  for (const [owner, claim] of Object.entries(parsed.namespaces ?? {})) {
    byId.set(`ns:${owner}`, { __namespace: true, owner, ...claim });
  }
}
const records = [...byId.values()].filter((r) => !r.__namespace);
const namespaces = [...byId.values()].filter((r) => r.__namespace);

const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);

const lines = [
  "-- generated by scripts/seed.mjs — do not edit",
  "DELETE FROM records;",
  "DELETE FROM skills_fts;",
  "DELETE FROM namespaces;",
];
for (const ns of namespaces) {
  lines.push(
    `INSERT INTO namespaces (owner, claimed_by, claimed_at, verified) VALUES (${q(ns.owner)}, ${q(ns.claimedBy)}, ${q(ns.claimedAt)}, ${ns.verified ? 1 : 0});`,
  );
}
for (const r of records) {
  const doc = toSearchDocument(r);
  const searchText = [doc.name, doc.description, doc.components.join(" "), doc.declarationText]
    .join(" ")
    .toLowerCase();
  lines.push(
    `INSERT INTO records (id, owner, name, kind, status, source_repo, ref, record_json, search_text, attestation_hash, ingested_at) VALUES (${q(r.id)}, ${q(r.owner)}, ${q(r.name)}, ${q(r.kind)}, ${q(r.status)}, ${q(r.sourceRepo ?? null)}, ${q(r.ref)}, ${q(JSON.stringify(r))}, ${q(searchText)}, ${q(r.attestation?.contentHash ?? null)}, ${q(r.ingestedAt)});`,
  );
  lines.push(
    `INSERT INTO skills_fts (id, name, description, components, declaration_text) VALUES (${q(doc.id)}, ${q(doc.name)}, ${q(doc.description)}, ${q(doc.components.join(" "))}, ${q(doc.declarationText)});`,
  );
}

const out = resolve(CF, "seed.sql");
writeFileSync(out, lines.join("\n") + "\n");
console.log(`seed: ${records.length} records, ${namespaces.length} namespaces → ${out}`);
