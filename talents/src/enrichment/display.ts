// Enrichment display view-model (Tranche 1: A–C page sections;
// Tranche 2: D generated panel data, E trust flags, completeness,
// and the structured API fragment). Converts a stored enrichment
// row into exactly what the skill page renders. Pure and shared —
// the Worker builds it from D1, tests build it from fixtures.
// Sections appear only when the layer produced them; provenance
// classes stay labelled at render time (source facts are
// "Source facts · as of", introspection is "live, introspected
// {date}", generated content is ALWAYS labelled generated, and the
// trust flags stay neutral facts).

import type { SkillRecord } from "../types.js";
import type {
  DriftStatus, EnrichmentRow, LayerState, McpPackageFacts, McpToolInfo, PluginMeta,
  SubInventoryEntry, TrustFlag,
} from "./types.js";
import { remoteEndpointOf } from "./layer-c.js";

export interface EnrichmentView {
  /** Served from our R2 copy — never hot-linked from the origin. */
  iconUrl?: string;
  sourceFacts?: {
    asOf: string;
    stars?: number;
    forks?: number;
    licenseSpdx?: string | null;
    language?: string | null;
    pushedAt?: string | null;
    archived?: boolean;
    contributorsLabel?: string;
    latestReleaseTag?: string;
    npmWeeklyDownloads?: number | null;
    npmMonthlyDownloads?: number | null;
    npmLatestVersion?: string | null;
    npmDeprecated?: boolean;
  };
  readmeExcerpt?: string;
  subInventory?: SubInventoryEntry[];
  subInventoryTruncated?: boolean;
  skillFacts?: {
    path: string;
    instructionLines: number;
    tokenEstimate: number;
    allowedTools?: string[];
    model?: string;
    license?: string;
    referencedFiles: number;
    externalUrls: string[];
  };
  pluginMeta?: PluginMeta;
  mcpPackage?: McpPackageFacts;
  tools?: {
    probedAt: string;
    endpointHost: string;
    serverName?: string;
    tools: McpToolInfo[];
    resourceCount?: number;
    promptCount?: number;
  };
  /** Class GENERATED (Layer D) — rendered only under a permanent
   *  "Generated by the registry…" label. */
  generated?: {
    generatedAt: string;
    model: string;
    oneLine: string;
    paragraph: string;
    categories: string[];
    tags: string[];
    useCases: string[];
    audience: string;
  };
  /** Class DERIVED (Layer E) — neutral factual lines, never a
   *  verdict. Absent when the scan found nothing… note: presence of
   *  this object with empty flags means "scanned, nothing found". */
  trustFlags?: {
    scannedAt: string;
    flags: TrustFlag[];
    drift: DriftStatus;
  };
  /** Per-layer states for the factual registry line + structured
   *  consumers. Set by enrichmentView whenever a row exists. */
  layers?: Record<"a" | "b" | "c" | "d" | "e", LayerState>;
  /** Completeness 0–100 (see completenessOf). */
  completeness?: number;
}

const hostOf = (url: string): string => {
  try { return new URL(url).host; } catch { return url; }
};

// ---------------------------------------------------------------------------
// Completeness (Tranche 2) — defined here, documented in README +
// ENRICHMENT.md. Each layer contributes a fixed share of the ideal
// enriched record; a layer earns full share for `done`, half for
// `partial` or `stale` (a verdict exists but is degraded), and
// nothing for `pending`/`none`. Layer C is NOT APPLICABLE to
// records without a public remote MCP endpoint — for those its
// weight is redistributed (the remaining weights renormalize to
// 100), so a skill/plugin is never penalized for a layer that
// cannot exist for it. Computed at read — no stored column, so the
// formula can evolve without a migration.
//   A (source facts) 25 · B (structure) 25 · C (introspection) 15
//   D (generated) 20 · E (trust) 15
// ---------------------------------------------------------------------------

export const COMPLETENESS_WEIGHTS = { a: 25, b: 25, c: 15, d: 20, e: 15 } as const;

const layerCredit = (state: LayerState): number =>
  state === "done" ? 1 : state === "partial" || state === "stale" ? 0.5 : 0;

export function completenessOf(record: SkillRecord, row: EnrichmentRow | null): number {
  if (!row) return 0;
  const cApplicable = remoteEndpointOf(record) !== null;
  const states = { a: row.aState, b: row.bState, c: row.cState, d: row.dState, e: row.eState };
  let earned = 0;
  let total = 0;
  for (const layer of ["a", "b", "c", "d", "e"] as const) {
    if (layer === "c" && !cApplicable) continue;
    total += COMPLETENESS_WEIGHTS[layer];
    earned += COMPLETENESS_WEIGHTS[layer] * layerCredit(states[layer]);
  }
  return total ? Math.round((earned / total) * 100) : 0;
}

export function enrichmentView(record: SkillRecord, row: EnrichmentRow | null): EnrichmentView | null {
  if (!row) return null;
  const view: EnrichmentView = {};

  if (row.a) {
    if (row.a.icon) view.iconUrl = `/assets/icon/${record.owner}/${record.name}`;
    const facts: NonNullable<EnrichmentView["sourceFacts"]> = { asOf: row.a.fetchedAt };
    let hasFacts = false;
    if (row.a.github) {
      const g = row.a.github;
      facts.stars = g.stars;
      facts.forks = g.forks;
      facts.licenseSpdx = g.licenseSpdx;
      facts.language = g.language;
      facts.pushedAt = g.pushedAt;
      facts.archived = g.archived;
      if (g.contributors !== null) {
        facts.contributorsLabel = g.contributorsCapped ? `${g.contributors}+` : String(g.contributors);
      }
      if (g.latestRelease) facts.latestReleaseTag = g.latestRelease.tag;
      hasFacts = true;
    }
    if (row.a.npm) {
      facts.npmWeeklyDownloads = row.a.npm.weeklyDownloads;
      facts.npmMonthlyDownloads = row.a.npm.monthlyDownloads;
      facts.npmLatestVersion = row.a.npm.latestVersion;
      facts.npmDeprecated = row.a.npm.deprecated;
      hasFacts = true;
    }
    if (hasFacts) view.sourceFacts = facts;
    if (row.a.readme?.excerpt) view.readmeExcerpt = row.a.readme.excerpt;
  }

  if (row.b) {
    if (row.b.subInventory?.length) {
      view.subInventory = row.b.subInventory;
      view.subInventoryTruncated = row.b.subInventoryTruncated;
    }
    if (row.b.skillParse) {
      const p = row.b.skillParse;
      view.skillFacts = {
        path: p.path,
        instructionLines: p.instructionLines,
        tokenEstimate: p.tokenEstimate,
        ...(p.frontmatter.allowedTools?.length ? { allowedTools: p.frontmatter.allowedTools } : {}),
        ...(p.frontmatter.model ? { model: p.frontmatter.model } : {}),
        ...(p.frontmatter.license ? { license: p.frontmatter.license } : {}),
        referencedFiles: p.referencedFiles.length,
        externalUrls: p.externalUrls,
      };
    }
    if (row.b.pluginMeta && Object.keys(row.b.pluginMeta).length) view.pluginMeta = row.b.pluginMeta;
    if (row.b.mcpPackage) view.mcpPackage = row.b.mcpPackage;
  }

  if (row.c && row.c.tools.length) {
    view.tools = {
      probedAt: row.c.probedAt,
      endpointHost: hostOf(row.c.endpoint),
      ...(row.c.serverInfo?.name ? { serverName: row.c.serverInfo.name } : {}),
      tools: row.c.tools,
      ...(row.c.resourceCount !== undefined ? { resourceCount: row.c.resourceCount } : {}),
      ...(row.c.promptCount !== undefined ? { promptCount: row.c.promptCount } : {}),
    };
  }

  if (row.dState === "done" && row.d && "oneLine" in row.d) {
    view.generated = {
      generatedAt: row.d.generatedAt,
      model: row.d.model,
      oneLine: row.d.oneLine,
      paragraph: row.d.paragraph,
      categories: row.d.categories,
      tags: row.d.tags,
      useCases: row.d.useCases,
      audience: row.d.audience,
    };
  }

  if (row.e && (row.eState === "done" || row.eState === "partial" || row.eState === "stale")) {
    view.trustFlags = {
      scannedAt: row.e.scannedAt,
      flags: row.e.flags,
      drift: row.e.drift.status,
    };
  }

  view.layers = { a: row.aState, b: row.bState, c: row.cState, d: row.dState, e: row.eState };
  view.completeness = completenessOf(record, row);

  return Object.keys(view).length ? view : null;
}

// ---------------------------------------------------------------------------
// Structured API fragment (/api/search, skill API, creator
// dashboard): the same labelling contract as the page — enrichment
// state is structured, and generated content nests under
// `generated`, NEVER merged into the record's source fields.
// ---------------------------------------------------------------------------

export interface ApiEnrichment {
  layers: Record<"a" | "b" | "c" | "d" | "e", LayerState>;
  completeness: number;
  generated?: {
    label: "generated";
    generatedAt: string;
    model: string;
    oneLine: string;
    paragraph: string;
    categories: string[];
    tags: string[];
    useCases: string[];
    audience: string;
  };
  trust?: {
    scannedAt: string;
    flags: TrustFlag[];
    drift: DriftStatus;
    lastVerifiedAt: string;
  };
}

export function apiEnrichment(record: SkillRecord, row: EnrichmentRow | null): ApiEnrichment | null {
  if (!row) return null;
  const view = enrichmentView(record, row);
  const out: ApiEnrichment = {
    layers: { a: row.aState, b: row.bState, c: row.cState, d: row.dState, e: row.eState },
    completeness: completenessOf(record, row),
  };
  if (view?.generated) out.generated = { label: "generated", ...view.generated };
  if (row.e && (row.eState === "done" || row.eState === "partial" || row.eState === "stale")) {
    out.trust = {
      scannedAt: row.e.scannedAt,
      flags: row.e.flags,
      drift: row.e.drift.status,
      lastVerifiedAt: row.e.lastVerifiedAt,
    };
  }
  return out;
}
